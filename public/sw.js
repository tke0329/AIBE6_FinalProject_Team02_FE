/*
 * 서비스워커 — 지금은 **설치 가능 요건만 채운다. 아무것도 캐시하지 않는다.**
 *
 * 왜 캐시를 안 넣었나
 *
 *   캐싱을 켜면 개발 중에 "고쳤는데 화면이 안 바뀐다"가 계속 생긴다. 지금은 두
 *   사람이 도메인 UI/UX를 동시에 고치는 중이라 그 혼란의 비용이 오프라인 지원의
 *   이득보다 크다. 그리고 캐싱은 배포 사고와 직결된다 — 낡은 워커가 낡은 HTML을
 *   붙잡으면 이미 사라진 JS 조각을 요청해서 흰 화면이 된다. 그건 "새 버전 있어요"
 *   갱신 안내와 한 묶음으로 들어가야 하고, 화면이 안정된 마무리 단계 일이다.
 *
 *   그래서 지금 워커가 하는 일은 하나뿐이다 — 안드로이드가 설치 배너를 띄우려면
 *   fetch 핸들러를 가진 워커를 요구하므로, 요청을 손대지 않고 그냥 흘려보낸다.
 *
 * 마무리 단계에 여기서 할 일
 *   1. 앱 셸·폰트(public/fonts/*.woff2 71개) 미리 캐시 — 재방문 즉시 로딩
 *   2. 새 워커 감지 → ToastProvider로 갱신 안내
 *   3. 오프라인 대체 화면
 */

// 새 워커를 대기시키지 않는다. 지금은 캐시가 없어 낡은 자원을 물고 있을 위험도 없다
self.addEventListener('install', () => self.skipWaiting())

// 이미 열려 있는 탭까지 새 워커가 맡는다
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()))

/*
 * 핸들러가 **있다는 것 자체**가 설치 가능 요건이다. respondWith를 부르지 않으면
 * 브라우저가 평소대로 네트워크로 보낸다 — 즉 동작이 지금과 완전히 같다.
 * 비워 두는 게 의도이므로 지우지 말 것
 */
self.addEventListener('fetch', () => {})
